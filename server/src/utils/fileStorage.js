import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';
import { v2 as cloudinary } from 'cloudinary';
import { env } from '../config/env.js';
import { ApiError } from './ApiError.js';

const useCloudinary = env.storageDriver === 'cloudinary';
if (useCloudinary) {
  cloudinary.config({
    cloud_name: env.cloudinary.cloudName,
    api_key: env.cloudinary.apiKey,
    api_secret: env.cloudinary.apiSecret,
    secure: true,
  });
}

const PNG_SIG = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]);

const TYPES = [
  { mime: 'application/pdf', ext: 'pdf', test: (b) => b.length > 5 && b.subarray(0, 5).toString('latin1') === '%PDF-' },
  { mime: 'image/png', ext: 'png', test: (b) => b.length > 8 && b.subarray(0, 8).equals(PNG_SIG) },
  { mime: 'image/jpeg', ext: 'jpg', test: (b) => b.length > 3 && b[0] === 0xff && b[1] === 0xd8 && b[2] === 0xff },
];

/** Detect the real file type from magic bytes (the client-supplied MIME type is not trusted). */
export function detectType(buffer) {
  return TYPES.find((t) => t.test(buffer)) || null;
}

const sanitizeName = (name = 'document') =>
  path.basename(String(name)).replace(/[^\w.\- ]/g, '_').slice(0, 100) || 'document';

/** Resolve a local stored name to an absolute path, refusing anything outside the upload directory. */
export function resolveStoredPath(storedName) {
  if (typeof storedName !== 'string' || !/^[a-f0-9]{32}\.(pdf|png|jpg)$/.test(storedName)) {
    throw new ApiError(404, 'Document not found');
  }
  const base = path.resolve(env.uploadDir);
  const full = path.resolve(base, storedName);
  if (!full.startsWith(base + path.sep)) throw new ApiError(404, 'Document not found');
  return full;
}

/**
 * Validates the content, then stores the document privately.
 * Cloudinary: uploaded with type "authenticated" — there is no public URL; it can only be
 * fetched with a signed, short-lived URL generated by this server for an authorised admin.
 */
export async function saveDocument(file) {
  const type = detectType(file.buffer);
  if (!type) throw new ApiError(400, 'Uploaded file content is not a valid PDF, JPG or PNG');
  const base = { originalName: sanitizeName(file.originalname), mimeType: type.mime, size: file.buffer.length };

  if (useCloudinary) {
    try {
      const result = await new Promise((resolve, reject) => {
        const stream = cloudinary.uploader.upload_stream(
          { folder: 'simbank/kyc', type: 'authenticated', resource_type: 'auto', unique_filename: true, overwrite: false },
          (err, res) => (err ? reject(err) : resolve(res))
        );
        stream.end(file.buffer);
      });
      return { ...base, provider: 'cloudinary', publicId: result.public_id, resourceType: result.resource_type, format: result.format };
    } catch (err) {
      console.error('[cloudinary] upload failed:', err?.message || err);
      throw new ApiError(502, 'Document upload failed. Please try again.');
    }
  }

  await fs.mkdir(env.uploadDir, { recursive: true, mode: 0o700 });
  const storedName = `${crypto.randomBytes(16).toString('hex')}.${type.ext}`;
  await fs.writeFile(path.join(env.uploadDir, storedName), file.buffer, { mode: 0o600, flag: 'wx' });
  return { ...base, provider: 'local', storedName };
}

/** Returns the document bytes. Documents saved before Cloudinary was enabled stay readable from disk. */
export async function readDocument(meta) {
  if (meta?.provider === 'cloudinary') {
    const url = cloudinary.utils.private_download_url(meta.publicId, meta.format || '', {
      resource_type: meta.resourceType || 'image',
      type: 'authenticated',
      expires_at: Math.floor(Date.now() / 1000) + 60,
    });
    const res = await fetch(url);
    if (!res.ok) {
      console.error('[cloudinary] download failed with status', res.status);
      throw new ApiError(502, 'Could not retrieve the document right now');
    }
    return Buffer.from(await res.arrayBuffer());
  }
  return fs.readFile(resolveStoredPath(meta?.storedName));
}

/** Best-effort cleanup (e.g. when registration fails after the upload succeeded). */
export async function deleteDocument(meta) {
  if (!meta) return;
  try {
    if (meta.provider === 'cloudinary') {
      await cloudinary.uploader.destroy(meta.publicId, { type: 'authenticated', resource_type: meta.resourceType || 'image', invalidate: true });
    } else {
      await fs.unlink(resolveStoredPath(meta.storedName));
    }
  } catch {
    /* ignore */
  }
}
